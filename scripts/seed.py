def main() -> None:
    seen: set[str] = set()
    items = []
    for ja, reading, pos, zh, ex_ja, ex_reading, ex_zh in RAW:
        if ja in seen:
            continue
        seen.add(ja)
        items.append(
            {
                "ja": ja,
                "reading": reading,
                "pos": pos,
                "zh": zh,
                "examples": [{"ja": ex_ja, "reading": ex_reading, "zh": ex_zh}],
            }
        )
    out = Path(__file__).resolve().parent.parent / "app" / "data" / "seed_words.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(items, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(items)} words -> {out}")


if __name__ == "__main__":
    main()
